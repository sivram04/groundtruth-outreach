"""Read-only view of the founder's mailbox, and what each message means for outreach.

Nothing here creates, changes, moves, labels or sends a message: Gmail is only listed and
read. Drafts are created in `gmail_drafts`, and nothing anywhere sends.

A reply's text is read only to tell a request to stop from any other answer. It is never
written to the Sheet; only the words that matched are recorded.
"""

import base64
import re
from datetime import datetime, timezone
from email.utils import getaddresses, parseaddr

from bs4 import BeautifulSoup
from googleapiclient.errors import HttpError

from outreach import drafting
from outreach.gmail_drafts import ACTION_HEADER

HEADERS = ["From", "To", "Cc", "Subject", "Date", "Message-ID", "In-Reply-To", "References",
           "Auto-Submitted", "X-Autoreply", "X-Autorespond", "X-Autogenerated", "Precedence",
           "X-Failed-Recipients", "Content-Type", ACTION_HEADER]

SENT, REPLIED, AUTO_REPLY, OPT_OUT, BOUNCED, DELAYED = (
    "SENT", "REPLIED", "AUTO_REPLY", "OPT_OUT", "BOUNCED", "DELAYED")


# --- reading ------------------------------------------------------------------------------

def list_ids(gmail, after, page_size=500):
    """Every message id after `after` (an aware datetime). Spam and trash are included: a reply
    the founder deleted, or one Gmail filed as spam, is still a reply."""
    query = f"after:{int(after.timestamp())} -in:drafts -in:chats"
    ids, page = [], None
    while True:
        args = {"userId": "me", "q": query, "maxResults": page_size, "includeSpamTrash": True}
        if page:
            args["pageToken"] = page
        result = gmail.users().messages().list(**args).execute()
        ids += [m["id"] for m in result.get("messages", [])]
        page = result.get("nextPageToken")
        if not page:
            return ids


def get(gmail, message_id, full=False):
    """One message: its headers, or with `full` its text too. None if it has gone since listing."""
    args = {"userId": "me", "id": message_id, "format": "full" if full else "metadata"}
    if not full:
        args["metadataHeaders"] = HEADERS
    try:
        return gmail.users().messages().get(**args).execute()
    except HttpError as exc:
        if getattr(exc.resp, "status", None) == 404:
            return None
        raise


def thread(gmail, thread_id):
    return gmail.users().threads().get(userId="me", id=thread_id, format="metadata",
                                       metadataHeaders=HEADERS).execute()


def drafts_in_thread(gmail, thread_id):
    """Ids of drafts already sitting in a thread."""
    found, page = [], None
    while True:
        args = {"userId": "me", "maxResults": 500}
        if page:
            args["pageToken"] = page
        result = gmail.users().drafts().list(**args).execute()
        found += [d["id"] for d in result.get("drafts", [])
                  if d.get("message", {}).get("threadId") == thread_id]
        page = result.get("nextPageToken")
        if not page:
            return found


def draft_exists(gmail, draft_id):
    try:
        gmail.users().drafts().get(userId="me", id=draft_id, format="minimal").execute()
        return True
    except HttpError as exc:
        if getattr(exc.resp, "status", None) == 404:
            return False
        raise


# --- the parts of a message ---------------------------------------------------------------

def header(message, name):
    for item in message.get("payload", {}).get("headers", []):
        if item.get("name", "").lower() == name.lower():
            return item.get("value", "")
    return ""


def addresses(value):
    return [address.strip().lower() for _, address in getaddresses([value or ""])
            if "@" in address]


def from_address(message):
    return parseaddr(header(message, "From"))[1].strip().lower()


def recipients(message):
    return addresses(header(message, "To")) + addresses(header(message, "Cc"))


def moment(message):
    return datetime.fromtimestamp(int(message["internalDate"]) / 1000, tz=timezone.utc)


def is_sent(message):
    return "SENT" in message.get("labelIds", [])


def _decode(data):
    return base64.urlsafe_b64decode(data + "=" * (-len(data) % 4)).decode("utf-8", errors="replace")


def _parts(payload):
    yield payload
    for part in payload.get("parts") or []:
        yield from _parts(part)


def body_text(message):
    """The message's text: its plain-text part, or the text of its HTML part."""
    plain, html = [], []
    for part in _parts(message.get("payload", {})):
        data = (part.get("body") or {}).get("data")
        if not data:
            continue
        if part.get("mimeType") == "text/plain":
            plain.append(_decode(data))
        elif part.get("mimeType") == "text/html":
            html.append(BeautifulSoup(_decode(data), "html.parser").get_text("\n"))
    return "\n".join(plain) if plain else "\n".join(html)


# Where a reply stops and the message it answers begins.
REPLY_HEADER = re.compile(r"^\s*On\b.*\bwrote:\s*$", re.I)
WRAPPED_REPLY_HEADER = re.compile(r"^.*\bwrote:\s*$", re.I)
ORIGINAL = re.compile(r"^\s*-{2,}\s*(?:Original Message|Forwarded message)\s*-{2,}", re.I)
OUTLOOK_RULE = re.compile(r"^\s*_{10,}\s*$")
FROM_LINE = re.compile(r"^\s*\*?From:\*?\s", re.I)
SENT_LINE = re.compile(r"^\s*\*?(?:Sent|Date):\*?\s", re.I)
# This system's own opt-out sentence, however a mail client wrapped it or curled its quotes.
OWN_OPT_OUT = re.compile(r"\s+".join(re.escape(word).replace("'", "['’]").replace('"', '["“”]')
                                     for word in drafting.OPT_OUT.split()), re.I)


def new_text(text):
    """What the replier wrote: quoted lines and the answered message are left out, and so is
    this system's own opt-out sentence if a client copied it back unquoted."""
    lines = (text or "").replace("\r\n", "\n").split("\n")
    kept = []
    for i, line in enumerate(lines):
        if (REPLY_HEADER.match(line) or ORIGINAL.match(line) or OUTLOOK_RULE.match(line)
                or (FROM_LINE.match(line) and any(SENT_LINE.match(n) for n in lines[i + 1:i + 5]))):
            break
        # "On Tue, Sep 22, 2026 at 1:18 PM Admin Lakshyaa <" + "admin@lakshyaa.ai> wrote:"
        if (line.strip().startswith("On ") and i + 1 < len(lines)
                and WRAPPED_REPLY_HEADER.match(lines[i + 1]) and not REPLY_HEADER.match(line)):
            break
        if line.lstrip().startswith(">"):
            continue
        kept.append(line)
    return OWN_OPT_OUT.sub(" ", "\n".join(kept)).strip()


# A request to stop. This is a word list, a heuristic: it errs toward treating a clear "no" as
# a request never to be written to again, because a missed opt-out is the worse mistake.
STOP = re.compile(
    r"\bno,?\s+thanks?\b|\bno\s+thank\s+you\b|\bunsubscribe\b|\bremove\s+(?:me|us|my|our)\b|"
    r"\btake\s+(?:me|us)\s+off\b|"
    r"\bstop\s+(?:emailing|e-mailing|contacting|sending|writing|reaching)\b|"
    r"\b(?:do\s+not|don'?t|dont)\s+(?:contact|email|e-mail|reach|write|send)\b|"
    r"\bnot\s+interested\b|\bno\s+interest\b|\bopt(?:-|\s)?(?:me\s+)?out\b|\bplease\s+stop\b|"
    r"\bleave\s+(?:me|us)\s+alone\b|\bwe(?:'ll|\s+will)\s+pass\b|\bpass\s+on\s+this\b", re.I)
BARE_STOP = {"no", "nope", "stop", "no thanks", "no thank you", "pass"}


def stop_words(text):
    """The words asking to stop, or '' when the reply does not ask."""
    found = STOP.search(text or "")
    if found:
        return " ".join(found.group(0).split())
    first = next((line for line in (text or "").splitlines() if line.strip()), "")
    bare = " ".join(re.findall(r"[a-z']+", first.lower()))
    return bare if bare in BARE_STOP else ""


AUTO_SUBJECT = re.compile(r"^\s*(?:automatic reply|auto(?:matic)?[\s-]?(?:reply|response)|"
                          r"autoreply|out of (?:the )?office|ooo\b|away from (?:the )?office|"
                          r"on vacation|i am out|i'm out|currently out)", re.I)
LEFT_COMPANY = re.compile(r"no longer (?:with|employed|work|at)|has left|left the company|"
                          r"no longer monitored|is no longer", re.I)


def is_auto_reply(message):
    automatic = header(message, "Auto-Submitted").strip().lower()
    if automatic and automatic != "no":
        return True
    if any(header(message, name) for name in ("X-Autoreply", "X-Autorespond", "X-Autogenerated")):
        return True
    if header(message, "Precedence").strip().lower() in {"auto_reply", "bulk", "junk"}:
        return True
    return bool(AUTO_SUBJECT.search(header(message, "Subject")))


BOUNCE_SENDER = re.compile(r"^(?:mailer-daemon|mail-daemon|mailerdaemon|postmaster)@", re.I)
DELAY_SUBJECT = re.compile(r"\(delay\)|\bdelayed\b|\bdelay(?:ed)? (?:notification|notice)\b|"
                           r"still being retried|delivery incomplete", re.I)


def is_bounce_notice(message):
    kind = header(message, "Content-Type").lower().replace(" ", "")
    return bool(BOUNCE_SENDER.match(from_address(message))
                or "report-type=delivery-status" in kind)


def bounce(message):
    """(BOUNCED or DELAYED, the addresses that failed, a short detail) for a delivery notice.

    Addresses come from the notice's own delivery report; `text_addresses` from its readable
    text are returned too, for matching when the report is missing."""
    failed = addresses(header(message, "X-Failed-Recipients"))
    codes = []
    for part in _parts(message.get("payload", {})):
        data = (part.get("body") or {}).get("data")
        if part.get("mimeType") == "message/delivery-status" and data:
            report = _decode(data)
            failed += [a.lower() for a in re.findall(
                r"(?:Final|Original)-Recipient:\s*rfc822;\s*<?([^\s<>;]+@[^\s<>;]+)>?", report, re.I)]
            codes += re.findall(r"^\s*Status:\s*([245]\.\d{1,3}\.\d{1,3})", report, re.I | re.M)
    text_addresses = sorted({a.lower().strip(".,;:<>()[]") for a in re.findall(
        r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}", body_text(message))})
    permanent = any(code.startswith("5") for code in codes)
    temporary = bool(codes) and all(code.startswith("4") for code in codes)
    kind = DELAYED if (temporary or (not permanent and DELAY_SUBJECT.search(
        header(message, "Subject")))) else BOUNCED
    detail = ("status " + ", ".join(sorted(set(codes)))) if codes else header(message, "Subject")[:80]
    return kind, sorted(set(failed)), text_addresses, detail


def received_kind(message):
    """(REPLIED, AUTO_REPLY or OPT_OUT, detail) for a message a lead sent. Needs the full message."""
    if is_auto_reply(message):
        left = LEFT_COMPANY.search(body_text(message) + " " + header(message, "Subject"))
        return AUTO_REPLY, ("says they may have left" if left else "")
    words = stop_words(new_text(body_text(message)))
    if words:
        return OPT_OUT, f'said "{words}"'
    return REPLIED, ""
